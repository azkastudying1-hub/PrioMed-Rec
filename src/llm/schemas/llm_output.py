"""
src/llm/schemas/llm_output.py
-------------------------------
Pydantic schema for validated LLM output.

PROJECT_CONTEXT §24 — LLM Output Contract.

Safety invariants enforced at schema level:
  - patient_id and encounter_id must match the input
  - risk_probability and priority are read-only (passed through, not generated by LLM)
  - verification_required is always True when flags are present
"""

from __future__ import annotations

from typing import List, Optional
from pydantic import BaseModel, Field


class DiscrepancyItem(BaseModel):
    type:                  str
    medication:            Optional[str] = None
    verification_required: bool = True


class LLMOutput(BaseModel):
    patient_id:          str
    encounter_id:        str
    priority:            str
    risk_probability:    float = Field(..., ge=0.0, le=1.0)
    summary:             str
    key_risk_factors:    List[str] = []
    potential_discrepancies: List[DiscrepancyItem] = []
    recommended_review_focus: List[str] = []
    verification_required: bool = True
    limitations:         List[str] = []
